// Rebuilds the service-area columns on the installation page from the real
// data. Run: node scripts/build-service-area.js
//
// WHY THIS EXISTS
//
// That block used to be a hand-written list of towns in invented distance
// bands, and it had drifted badly: Trenton and Humboldt (14 miles, no fee)
// were listed as 50-75 miles with a fee applying, while Gleason (29 miles,
// $15) was listed as local with no travel fee. Yorkville was listed and is
// not in the service area at all. The homepage town-checker, which reads the
// real data, contradicted this page directly.
//
// Same rule as the prices: one source of truth, everything else generated.
// Towns are grouped by what they actually cost to travel to, because that is
// the thing a customer is trying to find out.

const fs = require('fs');
const path = require('path');

const { J7_SERVICE_AREA, J7_PRICING } = require('../js/pricing.js');

const PAGE = path.join(__dirname, '..', 'pages', 'services-installation.html');
const START = '<!-- SERVICE-AREA:START (generated by scripts/build-service-area.js) -->';
const END = '<!-- SERVICE-AREA:END -->';

// Every distinct fee inside the radius, cheapest first. -1 means "beyond the
// radius, quote individually" and is handled in the prose, not the columns.
const fees = [...new Set(J7_SERVICE_AREA.filter(t => t.fee >= 0).map(t => t.fee))]
    .sort((a, b) => a - b);

const maxMilesFor = fee => {
    const band = J7_PRICING.travel.find(b => b.fee === fee);
    return band ? band.maxMiles : null;
};

const columns = fees.map(fee => {
    const towns = J7_SERVICE_AREA
        .filter(t => t.fee === fee)
        .sort((a, b) => a.miles - b.miles);
    const cap = maxMilesFor(fee);
    const heading = fee === 0
        ? `Within ${cap} miles`
        : `${cap ? 'Up to ' + cap + ' miles' : 'Further out'}`;
    const note = fee === 0
        ? '<strong>No travel fee</strong>'
        : `<strong>$${fee} travel fee</strong>`;
    const colour = fee === 0 ? 'var(--color-success)' : 'var(--color-text-gray)';

    // Prose rather than bullets. One tier has twenty-one towns and the others
    // ten, so a bulleted list made one column three times the height of its
    // neighbours. These are place names, not a checklist.
    return `                <div class="capability-column">
                    <h3>${heading}</h3>
                    <p>${towns.map(t => t.town).join(' &middot; ')}</p>
                    <p style="margin-top: 1rem; color: ${colour};">${note}</p>
                </div>`;
});

const block = `${START}
            <div class="capabilities-table">
${columns.join('\n')}
            </div>
            ${END}`;

let html = fs.readFileSync(PAGE, 'utf8');

const i = html.indexOf(START);
const j = html.indexOf(END);
if (i === -1 || j === -1) {
    console.error('Markers not found in services-installation.html - add them first.');
    process.exit(1);
}

html = html.slice(0, i) + block + html.slice(j + END.length);
fs.writeFileSync(PAGE, html);

const outside = J7_SERVICE_AREA.filter(t => t.fee < 0).map(t => t.town);
console.log('Rebuilt the service-area columns from js/pricing.js');
fees.forEach(fee => {
    const n = J7_SERVICE_AREA.filter(t => t.fee === fee).length;
    console.log(`  $${String(fee).padEnd(3)} ${String(n).padStart(3)} towns`);
});
console.log(`  beyond the radius, quoted individually: ${outside.join(', ')}`);
